"""User-facing bot messages. Override any of them by passing your own ``Texts``."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Texts:
    """Messages are Telegram HTML; ``{site}``, ``{pairing}`` and ``{name}`` are pre-escaped."""

    welcome: str = (
        "Это бот входа на сайт {site}.\nЧтобы войти, нажмите «Войти через Telegram» на сайте."
    )
    ask_contact: str = (
        "Вход на сайт {site}.\n"
        "Код на экране сайта: <b>{pairing}</b>.\n"
        "Если на сайте другой код или вы ничего не запрашивали, не продолжайте.\n\n"
        "Чтобы войти, поделитесь своим номером телефона кнопкой ниже."
    )
    share_button: str = "Поделиться номером"
    invalid_code: str = (
        "Ссылка недействительна или устарела. Вернитесь на сайт и запросите вход заново."
    )
    taken: str = (
        "Эта ссылка уже открыта в другом аккаунте Telegram. Запросите вход на сайте заново."
    )
    finished: str = "Этот вход уже обработан. Вернитесь на сайт."
    rate_limited: str = "Слишком много неверных ссылок. Попробуйте позже."
    foreign_contact: str = (
        "Можно поделиться только своим номером, и только кнопкой «Поделиться номером»: "
        "пересланные и чужие контакты не принимаются."
    )
    no_active_code: str = "Сначала нажмите «Войти через Telegram» на сайте."
    confirmed: str = "Готово{name}. Вернитесь на сайт, вход завершится автоматически."
    not_found: str = (
        "Этот номер не найден среди клиентов. Если вы оформляли заказ на другой номер, "
        "войдите с ним или напишите в поддержку."
    )
    review_required: str = (
        "Ваш профиль требует ручной проверки, поэтому автоматический вход недоступен. "
        "Напишите в поддержку, мы поможем."
    )
    unavailable: str = "Вход временно недоступен. Попробуйте позже."
    other: str = "Я принимаю только вход с сайта. Нажмите «Войти через Telegram» на сайте."
